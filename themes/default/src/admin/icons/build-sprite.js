/**
 * Builds the independent admin and public sprites from their own icon lists.
 *
 *     npm run icons                 # both sprites
 *     npm run icons -- public       # public sprite and Twig name map only
 *     npm run icons -- admin        # admin sprite only
 *
 * The sprite is a committed static file of the theme, served by PHP like the other icons, so it
 * is rebuilt by hand after the list changes rather than on every build. A name Lucide does not
 * have fails the run instead of leaving a hole in the sprite.
 *
 * The symbols carry only their shapes: fill, stroke and its width come from the <svg> that uses
 * them (.admin-icon or .site-icon--lucide), so one sprite serves every size and weight.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const lucideIcons = join(dirname(createRequire(import.meta.url).resolve('lucide-static/package.json')), 'icons');
const { version } = JSON.parse(readFileSync(join(lucideIcons, '../package.json'), 'utf8'));

const targets = {
    admin: {
        list: join(here, 'icons.json'),
        sprite: join(here, '../../../../../public/themes/default/assets/icons/admin.svg'),
    },
    public: {
        list: join(here, '../../icons/icons.json'),
        sprite: join(here, '../../../../../public/themes/default/assets/icons/public.svg'),
        map: join(here, '../../../templates/components/icon-map.twig'),
    },
};

function symbol(name) {
    let source;

    try {
        source = readFileSync(join(lucideIcons, `${name}.svg`), 'utf8');
    } catch {
        throw new Error(`Lucide has no icon named "${name}", see https://lucide.dev/icons/`);
    }

    const shapes = source
        .replace(/<!--[\s\S]*?-->/g, '')
        .replace(/^[\s\S]*?<svg[^>]*>/, '')
        .replace(/<\/svg>\s*$/, '')
        .trim()
        .split('\n')
        .map((line) => '        ' + line.trim())
        .join('\n');

    return `    <symbol id="${name}" viewBox="0 0 24 24">\n${shapes}\n    </symbol>`;
}

function build(target) {
    const definition = JSON.parse(readFileSync(target.list, 'utf8'));
    const names = Array.isArray(definition) ? definition : definition.icons;
    const aliases = Array.isArray(definition) ? {} : definition.aliases;

    if (!Array.isArray(names) || names.length === 0 || new Set(names).size !== names.length
        || names.some(name => typeof name !== 'string' || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name))) {
        throw new Error(`${target.list}: expected a nonempty list of unique Lucide names.`);
    }

    if (!aliases || typeof aliases !== 'object' || Array.isArray(aliases)
        || Object.entries(aliases).some(([alias, name]) => !/^[a-z0-9_-]+$/.test(alias) || !names.includes(name))) {
        throw new Error(`${target.list}: aliases must point to icons in this list.`);
    }

    const symbols = names.map(symbol);

    writeFileSync(
        target.sprite,
        `<!-- Lucide v${version}, ISC license. Generated by themes/default/src/admin/icons/build-sprite.js, do not edit. -->\n`
        + `<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join('\n')}\n</svg>\n`,
    );

    if (target.map) {
        writeFileSync(
            target.map,
            `{# Generated from themes/default/src/icons/icons.json by npm run icons; do not edit. #}\n`
            + `{% macro resolve(name) %}\n`
            + `    {% set names = ${JSON.stringify(names, null, 4).replace(/\n/g, '\n    ')} %}\n`
            + `    {% set aliases = ${JSON.stringify(aliases, null, 4).replace(/\n/g, '\n    ')} %}\n`
            + `    {{- aliases[name]|default(name in names ? name : '') -}}\n`
            + `{% endmacro %}\n`,
        );
    }

    console.log(`${names.length} icons written to ${target.sprite}`);
}

const selected = process.argv.slice(2);
for (const name of selected.length ? selected : Object.keys(targets)) {
    if (!Object.hasOwn(targets, name)) {
        throw new Error(`Unknown sprite "${name}"; choose admin or public.`);
    }

    build(targets[name]);
}
